      fl.connect(g);
      E.tone("sine", f, 1, t, 3.2, fl, -4); // two detuned strings
      E.tone("sine", f, 0.8, t, 3.2, fl, 5);
      E.tone("triangle", f * 2, 0.25, t, 2, fl);
      E.tone("sine", f * 4, 0.08, t + 0.02, 1.6, fl); // shimmer
      E.tone("sine", f * 2, 0.18, t + 0.28, 2.2, fl); // ghost echo, an octave up
      g.gain.setValueAtTime(0.0001, t);
      g.gain.exponentialRampToValueAtTime(v * 0.8, t + 0.03); // soft attack
      g.gain.exponentialRampToValueAtTime(0.0001, t + 3.4);
      send.gain.value = 0.9;
      g.connect(send);
